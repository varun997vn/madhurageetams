import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const c = await b.newContext({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 2 })
const p = await c.newPage()
const BASE = 'http://localhost:4173/madhurageetams/'
await p.goto(BASE, { waitUntil: 'networkidle' })
await p.screenshot({ path: 'shots/1-unlock.png' })
await p.fill('#password', process.env.MG_PASSWORD)
await p.click('button[type=submit]')
await p.waitForSelector('.occasion-card', { timeout: 60000 })
await p.waitForTimeout(2500)
await p.screenshot({ path: 'shots/2-occasions.png' })
await p.goto(BASE + '#/browse?deity=0', { waitUntil: 'networkidle' })
await p.waitForSelector('.result-row', { timeout: 30000 })
await p.waitForTimeout(1500)
await p.screenshot({ path: 'shots/3-browse.png' })
await p.click('.result-title')
await p.waitForSelector('.lyrics', { timeout: 30000 })
await p.waitForTimeout(800)
await p.screenshot({ path: 'shots/4-song.png' })
await p.goto(BASE + '#/insights', { waitUntil: 'networkidle' })
await p.waitForSelector('.bar-row', { timeout: 30000 })
await p.waitForTimeout(1500)
await p.screenshot({ path: 'shots/5-insights.png' })
await b.close()
